function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * 辞書に基づいて文字起こしを補正する。
 * @returns {{ text: string, corrections: Array<{from: string, to: string, count: number}> }}
 */
export function applyGlossary(text, glossary = DEFAULT_GLOSSARY) {
  let out = text;
  const corrections = [];
  // 長いパターンから先に置換（部分一致の衝突を避ける）
  const sorted = [...glossary]
    .filter(([from, to]) => from && to && from !== to)
    .sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of sorted) {
    // 既に正しい表記になっている箇所を退避してから置換（「床ずれ」→「褥瘡（床ずれ）」の二重置換防止）
    const kept = out.split(to);
    let count = 0;
    out = kept
      .map((seg) =>
        seg.replace(new RegExp(escapeRegExp(from), "g"), () => {
          count++;
          return to;
        }),
      )
      .join(to);
    if (count > 0) corrections.push({ from, to, count });
  }
  return { text: out, corrections };
}

/** "誤,正" 形式の行テキストを辞書配列に変換 */
export function parseGlossaryText(src) {
  return src
    .split(/\r?\n/)
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith("#"))
    .map((l) => l.split(/[,，\t→]/).map((s) => s.trim()))
    .filter((p) => p.length >= 2 && p[0] && p[1])
    .map(([a, b]) => [a, b]);
}
